/**
 * Restore accepts every BIP39 length (12, 15, 18, 21, 24 words). Vectors in
 * src/test/resources/bip39-vectors.json: the official Trezor python-mnemonic set (12, 18, 24 words,
 * passphrase "TREZOR"; file SHA-256 recorded there), plus 15 and 21-word vectors generated by that
 * same reference implementation (python-mnemonic 0.21) after it reproduced the official set. Each
 * one: entropy → words, words → seed with the passphrase, seed → master xprv.
 */
public final class Bip39LengthsTest {
    static List<String[]> vectors() throws Exception {
        JSONObject f;
        try (InputStream in = Bip39LengthsTest.class.getClassLoader().getResourceAsStream("bip39-vectors.json")) {
            if (in == null) throw new IllegalStateException("bip39-vectors.json missing from test resources");
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            byte[] buffer = new byte[8192];
            for (int n; (n = in.read(buffer)) > 0; ) out.write(buffer, 0, n);
            f = new JSONObject(new String(out.toByteArray(), StandardCharsets.UTF_8));
        }
        assertEquals("TREZOR", f.getString("passphrase"));
        List<String[]> all = new ArrayList<>();
        for (String set : new String[] {"official", "generated"}) {
            JSONArray list = f.getJSONObject(set).getJSONArray("vectors");
            for (int i = 0; i < list.length(); i++) {
                JSONArray v = list.getJSONArray(i);
                all.add(new String[] {v.getString(0), v.getString(1), v.getString(2), v.getString(3)});
            }
        }
        assertEquals(32, all.size());
        return all;
    }

    @Test public void everyLengthHasVectors() throws Exception {
        Set<Integer> lengths = new TreeSet<>();
        for (String[] v : vectors()) lengths.add(v[1].split(" ").length);
        assertEquals(new TreeSet<>(Arrays.asList(12, 15, 18, 21, 24)), lengths);
    }

    @Test public void entropyWordsSeedAndMasterKeyMatchTheVectors() throws Exception {
        for (String[] v : vectors()) {
            String entropy = v[0], words = v[1], seed = v[2], xprv = v[3];
            assertEquals(words, MnemonicUtils.generateMnemonic(Numeric.hexStringToByteArray(entropy)));
            assertEquals("restore accepts the " + words.split(" ").length + "-word vector", words, SeedRestore.validate(words));
            assertEquals(words, SeedRestore.validate(words, words.split(" ").length));
            assertEquals(seed, Numeric.toHexStringNoPrefix(SeedVault.bip39Seed(words, "TREZOR")));
            AccountsTest.assertMaster(words, "TREZOR", xprv);
        }
    }

    @Test public void theChosenWordCountMustMatch() throws Exception {
        String twelve = TestKeys.ABANDON_12;
        try {
            SeedRestore.validate(twelve, 24);
            fail("12 words typed after choosing 24");
        } catch (SeedRestore.RestoreException e) {
            assertEquals("Expected 24 words, found 12", e.getMessage());
        }
        try {
            SeedRestore.validate("", 15);
            fail();
        } catch (SeedRestore.RestoreException e) {
            assertEquals("Enter your 15-word recovery phrase", e.getMessage());
        }
        try { SeedRestore.validate(twelve, 13); fail("13 is not a BIP39 length"); } catch (IllegalArgumentException expected) { }
    }

    /** web3j's own check accepts 3, 6 and 9-word phrases (32-96 bits): the phone never does. */
    @Test public void shortAndOddLengthsAreRefusedEverywhere() throws Exception {
        for (int bytes : new int[] {4, 8, 12}) {
            String tooShort = encode(new byte[bytes]);
            int n = tooShort.split(" ").length;
            assertEquals(bytes * 3 / 4, n);
            try {
                SeedRestore.validate(tooShort);
                fail(n + " words accepted");
            } catch (SeedRestore.RestoreException e) {
                assertEquals("Expected 12, 15, 18, 21 or 24 words, found " + n, e.getMessage());
            }
            try { SeedVault.bip39Seed(tooShort, ""); fail(n + " words derived"); } catch (IllegalArgumentException expected) { }
        }
        for (int n : new int[] {0, 11, 13, 16, 23, 25, 27}) assertFalse(SeedRestore.isWordCount(n));
        for (int n : SeedRestore.WORD_COUNTS) assertTrue(SeedRestore.isWordCount(n));
        assertEquals(24, SeedRestore.CREATE_WORD_COUNT);
    }

    /** BIP39 encoding of any 32-bit multiple of entropy (web3j's generateMnemonic refuses under 128 bits). */
    private static String encode(byte[] entropy) throws Exception {
        byte[] hash = java.security.MessageDigest.getInstance("SHA-256").digest(entropy);
        int bits = entropy.length * 8, cs = bits / 32;
        List<String> list = MnemonicUtils.getWords();
        StringBuilder out = new StringBuilder();
        for (int w = 0; w < (bits + cs) / 11; w++) {
            int index = 0;
            for (int b = w * 11; b < w * 11 + 11; b++) {
                int bit = b < bits ? (entropy[b / 8] >> (7 - b % 8)) & 1 : (hash[(b - bits) / 8] >> (7 - (b - bits) % 8)) & 1;
                index = index << 1 | bit;
            }
            if (out.length() > 0) out.append(' ');
            out.append(list.get(index));
        }
        return out.toString();
    }

    @Test public void theTestEncoderIsBip39() throws Exception {
        for (String[] v : vectors()) assertEquals(v[1], encode(Numeric.hexStringToByteArray(v[0])));
    }

    /** A wrong word or a wrong last (checksum) word is refused at every length. */
    @Test public void checksumIsCheckedAtEveryLength() throws Exception {
        for (String[] v : vectors()) {
            String[] w = v[1].split(" ");
            String last = w[w.length - 1];
            w[w.length - 1] = last.equals("abandon") ? "ability" : "abandon";
            String bad = String.join(" ", w);
            if (MnemonicUtils.validateMnemonic(bad)) continue; // 1 in 2^(checksum bits) still valid: not a checksum test
            try {
                SeedRestore.validate(bad);
                fail("bad checksum accepted: " + bad);
            } catch (SeedRestore.RestoreException e) {
                assertTrue(e.getMessage(), e.getMessage().contains("checksum"));
            }
        }
    }

    @Test public void backupSpotCheckAndPagesWorkForEveryLength() throws Exception {
        for (int n : SeedRestore.WORD_COUNTS) {
            String[] words = MnemonicUtils.generateMnemonic(new byte[n * 4 / 3]).split(" ");
            assertEquals(n, words.length);
            BackupCheck.Challenge c = new BackupCheck.Challenge(words, new SecureRandom());
            for (int i = 0; i < c.total(); i++) {
                int position = c.position();
                assertTrue(position >= 0 && position < n);
                assertTrue(c.answer(words[position]));
            }
            assertTrue(c.complete());
            int per = BackupScreens.wordsPerPage(n);
            assertEquals("every phrase page is full", 0, n % per);
        }
        assertEquals(3, 12 / BackupScreens.wordsPerPage(12));
        assertEquals(7, 21 / BackupScreens.wordsPerPage(21));
        assertEquals(6, 24 / BackupScreens.wordsPerPage(24));
        try { new BackupCheck.Challenge(new String[9], new SecureRandom()); fail(); } catch (IllegalArgumentException expected) { }
    }

    /** SeedQR is defined for 12 and 24 words only: 21/25 (compact) and 25/29 (standard) modules. */
    @Test public void seedQrOnlyFor12And24Words() throws Exception {
        assertEquals(21, SeedQr.gridSize(12, SeedQr.Format.COMPACT));
        assertEquals(25, SeedQr.gridSize(12, SeedQr.Format.STANDARD));
        assertEquals(25, SeedQr.gridSize(24, SeedQr.Format.COMPACT));
        assertEquals(29, SeedQr.gridSize(24, SeedQr.Format.STANDARD));
        for (int n : SeedRestore.WORD_COUNTS) {
            String[] words = MnemonicUtils.generateMnemonic(new byte[n * 4 / 3]).split(" ");
            assertEquals(n == 12 || n == 24, SeedQr.supports(n));
            for (SeedQr.Format format : SeedQr.Format.values()) {
                if (SeedQr.supports(n)) {
                    assertEquals(SeedQr.gridSize(n, format), SeedQr.encode(words, format).size);
                } else {
                    try { SeedQr.encode(words, format); fail(n + "-word SeedQR"); } catch (IllegalArgumentException expected) { }
                }
            }
        }
    }

    /** The phrase pages and the SeedQR screen follow the phrase's length, and the restore UI asks for it first. */
    @Test public void screensFollowThePhraseLength() throws Exception {
        String backup = SourceGuard.source("BackupScreens.java");
        assertFalse("no fixed six pages", backup.contains("of 6"));
        assertTrue(backup.contains("if (replacementCandidate == null && SeedQr.supports(backupWords.length)) pages.action(root, \"Show as SeedQR\""));
        assertTrue(backup.contains("if (!SeedQr.supports(backupWords.length)) {"));
        String setup = SourceGuard.source("SetupScreens.java");
        assertTrue(setup.contains("if (restoreCount == 0) { showRestoreWordCount(); return; }"));
        assertTrue(setup.contains("mnemonic = SeedRestore.validate(raw, count);"));
        assertFalse(SourceGuard.anyContains("SeedRestore.WORD_COUNT;"));
    }
}
