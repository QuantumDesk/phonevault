package dev.phonevault.signer;

import static org.junit.Assert.assertArrayEquals;
import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertTrue;
import static org.junit.Assert.fail;

import org.json.JSONArray;
import org.json.JSONObject;
import org.junit.Test;
import org.web3j.crypto.Credentials;
import org.web3j.crypto.Hash;
import org.web3j.crypto.Keys;
import org.web3j.crypto.Sign;
import org.web3j.utils.Numeric;

import java.io.ByteArrayOutputStream;
import java.io.InputStream;
import java.math.BigInteger;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;

/**
 * The shared vectors in src/test/resources/message-signing-vectors.json (generated by ethers v6
 * and cross-checked against eth-sig-util; the companion's Rust tests read the same file). Every
 * digest, domain separator, message hash and signature must match byte for byte, and every
 * entry under "rejections" must be refused.
 */
public final class MessageSigningVectorsTest {
    /** keccak256("cow"): the EIP-712 example key. TEST KEY ONLY. */
    static final Credentials COW = Credentials.create(
            Numeric.toHexString(Hash.sha3("cow".getBytes(StandardCharsets.US_ASCII))));

    static JSONObject fixture() throws Exception {
        try (InputStream in = MessageSigningVectorsTest.class.getClassLoader()
                .getResourceAsStream("message-signing-vectors.json")) {
            if (in == null) throw new IllegalStateException("fixture missing from test resources");
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            byte[] buffer = new byte[8192];
            for (int n; (n = in.read(buffer)) > 0; ) out.write(buffer, 0, n);
            return new JSONObject(new String(out.toByteArray(), StandardCharsets.UTF_8));
        }
    }

    static String vector(String name, String field) throws Exception {
        JSONArray vectors = fixture().getJSONArray("vectors");
        for (int i = 0; i < vectors.length(); i++) {
            if (vectors.getJSONObject(i).getString("name").equals(name)) return vectors.getJSONObject(i).getString(field);
        }
        throw new IllegalArgumentException("no vector " + name);
    }

    @Test public void cowKeyIsTheEip712ExampleSigner() throws Exception {
        assertEquals(fixture().getString("signer"), COW.getAddress());
        assertEquals("0xcd2a3d9f938e13cd947ec05abc7fe734df8dd826", COW.getAddress());
    }

    @Test public void everyVectorMatchesDigestAndSignatureByteForByte() throws Exception {
        JSONArray vectors = fixture().getJSONArray("vectors");
        assertTrue(vectors.length() >= 11);
        for (int i = 0; i < vectors.length(); i++) {
            JSONObject v = vectors.getJSONObject(i);
            String name = v.getString("name");
            byte[] digest;
            if (v.getString("kind").equals("typed")) {
                Eip712.TypedData t = Eip712.parse(v.getString("typedData"));
                assertEquals(name + " domain separator", v.getString("domainSeparator"), Numeric.toHexString(t.domainSeparator()));
                assertEquals(name + " message hash", v.getString("messageHash"), Numeric.toHexString(t.messageHash()));
                digest = t.digest();
            } else {
                digest = PersonalMessage.of(Numeric.hexStringToByteArray(v.getString("message"))).digest();
            }
            assertEquals(name + " digest", v.getString("digest"), Numeric.toHexString(digest));
            JSONObject response = MessageApprovalSession.sign("vector", digest, COW);
            // RFC 6979 deterministic nonces: web3j and ethers must produce the identical signature.
            assertEquals(name + " signature", v.getString("signature"), response.getString("signature"));
            assertEquals(Numeric.toHexString(digest), response.getString("digest"));
            assertEquals(recover(digest, response.getString("signature")), COW.getAddress());
        }
    }

    @Test public void everySharedRejectionIsRefused() throws Exception {
        JSONArray rejections = fixture().getJSONArray("rejections");
        assertTrue(rejections.length() >= 50);
        for (int i = 0; i < rejections.length(); i++) {
            JSONObject r = rejections.getJSONObject(i);
            try {
                Eip712.parse(r.getString("typedData"));
                fail("accepted " + r.getString("name"));
            } catch (Eip712.InvalidTypedData expected) {
                // refused, as the companion must also do
            }
        }
    }

    @Test public void mailEncodeTypeAndTypeHashMatchTheEip() throws Exception {
        Eip712.TypedData t = Eip712.parse(vector("eip712-mail", "typedData"));
        assertEquals("Mail(Person from,Person to,string contents)Person(string name,address wallet)", t.encodeType("Mail"));
        assertEquals("0xa0cedeb2dc280ba39b857546d74f5549c3a1d7bdc2dd96bf881f76108e23dac2",
                Numeric.toHexString(Hash.sha3(t.encodeType("Mail").getBytes(StandardCharsets.UTF_8))));
        assertEquals("0xf2cee375fa42b42143804025fc449deafd50cc031ca257e0b194a650a912090f", Numeric.toHexString(t.domainSeparator()));
        assertEquals("0xc52c0ee5d84264471806290a3f2c4cecfc5490626bf912d01f240d7a274b371e", Numeric.toHexString(t.messageHash()));
        assertEquals("0xbe609aee343fb3c4b28e1df9e632fca64fcfaede20f02e86244efddf30957bd2", Numeric.toHexString(t.digest()));
        // The signature published in EIP-712 for this message and key: v = 28.
        JSONObject response = MessageApprovalSession.sign("mail", t.digest(), COW);
        assertEquals("0x4355c47d63924e8a72e509b65029052eb6c299d53a04e167c5775fd466751c9d"
                + "07299936d304c153f6443dfa05f40ff007d72911b6f72307f996231605b91562" + "1c",
                response.getString("signature"));
    }

    @Test public void nestedArraysEncodeTypeSortsReferencedStructs() throws Exception {
        Eip712.TypedData t = Eip712.parse(vector("sig-util-v4-nested-arrays", "typedData"));
        assertEquals("Mail(Person from,Person[] to,string contents)Person(string name,address[] wallets)", t.encodeType("Mail"));
        Eip712.TypedData k = Eip712.parse(vector("all-atomic-types", "typedData"));
        assertEquals("Kitchen(int8 i8,int256 i256,uint8 u8,uint256 u256,uint160 u160hex,bytes1 b1,bytes32 b32,bytes dyn,"
                + "bytes empty,bool yes,bool no,string text,uint256[2] fixed,address[][] grid,Leaf[2] leaves,int16[] none,int64 neg)"
                + "Leaf(bool flag,string note)", k.encodeType("Kitchen"));
        assertEquals(BigInteger.valueOf(-128), k.message.get("i8").integer());
        assertEquals(BigInteger.valueOf(8453), k.domainChainId());
        assertEquals(3, k.message.get("grid").elements().size());
        assertEquals(0, k.message.get("grid").elements().get(1).elements().size());
    }

    @Test public void signatureIsLowSAndRecoverable() throws Exception {
        byte[] digest = Hash.sha3("anything".getBytes(StandardCharsets.US_ASCII));
        String signature = MessageApprovalSession.sign("x", digest, COW).getString("signature");
        byte[] sig = Numeric.hexStringToByteArray(signature);
        assertEquals(65, sig.length);
        assertTrue(sig[64] == 27 || sig[64] == 28);
        BigInteger s = new BigInteger(1, Arrays.copyOfRange(sig, 32, 64));
        BigInteger halfN = Sign.CURVE_PARAMS.getN().shiftRight(1);
        assertTrue("EIP-2 low-s", s.compareTo(halfN) <= 0);
    }

    static String recover(byte[] digest, String signatureHex) throws Exception {
        byte[] sig = Numeric.hexStringToByteArray(signatureHex);
        Sign.SignatureData data = new Sign.SignatureData(sig[64], Arrays.copyOfRange(sig, 0, 32), Arrays.copyOfRange(sig, 32, 64));
        return "0x" + Keys.getAddress(Sign.signedMessageHashToKey(digest, data));
    }
}
