#!/usr/bin/env python3
"""Export a reproducible repo manifest without pinning unpublished local commits."""

from __future__ import annotations

import argparse
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path


ALLOWED_DIRTY_PROJECTS = {
    "build/make",
    "device/google/crosshatch",
    "frameworks/base",
}
ALLOWED_UNPUBLISHED_PROJECTS = {"frameworks/base"}


def git(source: Path, project: str, *args: str, check: bool = True) -> str:
    result = subprocess.run(
        ["git", "-C", str(source / project), *args],
        check=check,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    return result.stdout.strip()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    source = args.source.resolve()
    output = args.output.resolve()

    raw = subprocess.run(
        ["repo", "manifest", "-r", "--pretty", "-o", "-"],
        cwd=source,
        check=True,
        text=True,
        stdout=subprocess.PIPE,
    ).stdout
    root = ET.fromstring(raw)

    rewritten: list[tuple[str, str, str]] = []
    for project in root.findall("project"):
        path = project.get("path") or project.get("name")
        revision = project.get("revision")
        if not path or not revision or not (source / path).is_dir():
            continue

        status = git(source, path, "status", "--porcelain")
        if status and path not in ALLOWED_DIRTY_PROJECTS:
            raise SystemExit(f"unexpected dirty repo while pinning manifest: {path}")

        containing = git(source, path, "branch", "-r", "--contains", revision)
        if containing:
            continue
        if path not in ALLOWED_UNPUBLISHED_PROJECTS:
            raise SystemExit(f"unpublished commit outside patch allowlist: {path} {revision}")

        upstream = project.get("upstream")
        if not upstream or not upstream.startswith("refs/heads/"):
            raise SystemExit(f"cannot resolve upstream branch for {path}")
        branch = upstream.removeprefix("refs/heads/")
        base = git(source, path, "rev-parse", f"refs/remotes/m/{branch}")
        project.set("revision", base)
        rewritten.append((path, revision, base))

    ET.indent(root, space="  ")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<!-- Generated by generate-pinned-manifest.py; local changes are replayed from vault-os/patches. -->\n'
        + ET.tostring(root, encoding="unicode")
        + "\n",
        encoding="utf-8",
    )
    for path, local, base in rewritten:
        print(f"rewrote unpublished {path}: {local} -> {base}", file=sys.stderr)
    print(f"wrote {output} with {len(root.findall('project'))} pinned projects")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
